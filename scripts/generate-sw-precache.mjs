#!/usr/bin/env node
/**
 * Writes public/sw-precache.js: the list of routes the service worker
 * precaches at install, plus a build version that names its caches.
 *
 * Runs automatically before `npm run build` (the "prebuild" script) and can be
 * run standalone: `node scripts/generate-sw-precache.mjs`.
 *
 * The service worker cannot import TypeScript, so tool ids are read from
 * src/tools/registry.ts textually and cross-checked against the route folders
 * in src/app/tools/ so we never precache a URL that would 404. If this file is
 * missing at runtime, public/sw.js falls back to discovering routes from /tools.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = join(ROOT, 'src', 'tools', 'registry.ts');
const TOOL_ROUTES = join(ROOT, 'src', 'app', 'tools');
const OUT = join(ROOT, 'public', 'sw-precache.js');

// Must match categorySlug() in src/tools/registry.ts.
const categorySlug = (category) =>
  category.toLowerCase().replace(/&/g, '').replace(/\s+/g, '-').replace(/--+/g, '-').trim();

function readRegistry() {
  const source = readFileSync(REGISTRY, 'utf8');

  const toolsStart = source.indexOf('export const tools');
  const toolsEnd = source.indexOf('];', toolsStart);
  if (toolsStart === -1 || toolsEnd === -1) throw new Error('could not find `export const tools` in registry.ts');
  const ids = [...source.slice(toolsStart, toolsEnd).matchAll(/\bid:\s*['"]([a-z0-9-]+)['"]/g)].map((m) => m[1]);

  const catMatch = source.match(/export const categories[^=]*=\s*\[([^\]]*)\]/);
  const categories = catMatch ? [...catMatch[1].matchAll(/['"]([^'"]+)['"]/g)].map((m) => m[1]) : [];

  return { ids, categories };
}

function main() {
  const { ids, categories } = readRegistry();
  if (ids.length === 0) throw new Error('no tool ids found in registry.ts');

  const missing = ids.filter((id) => !existsSync(join(TOOL_ROUTES, id, 'page.tsx')));
  if (missing.length) {
    console.warn(`[sw-precache] skipping ids without a route folder: ${missing.join(', ')}`);
  }

  const routes = [
    '/',
    '/tools',
    '/offline',
    ...categories.map((c) => `/tools/categories/${categorySlug(c)}`),
    ...ids.filter((id) => !missing.includes(id)).map((id) => `/tools/${id}`),
  ];
  const unique = [...new Set(routes)];

  // A new version per build: Next.js chunk hashes change on every build, so the
  // service worker must re-precache and drop the previous caches each deploy.
  const buildId = process.env.VERCEL_GIT_COMMIT_SHA || process.env.GITHUB_SHA || `${Date.now()}`;
  const version = createHash('sha256').update(`${buildId}\n${unique.join('\n')}`).digest('hex').slice(0, 12);

  const body =
    '// AUTO-GENERATED by scripts/generate-sw-precache.mjs. Do not edit.\n' +
    `self.__SW_PRECACHE = ${JSON.stringify({ version, routes: unique }, null, 2)};\n`;
  writeFileSync(OUT, body);
  console.log(`[sw-precache] wrote public/sw-precache.js (version ${version}, ${unique.length} routes)`);
}

try {
  main();
} catch (err) {
  console.error(`[sw-precache] failed: ${err instanceof Error ? err.message : err}`);
  process.exit(1);
}
